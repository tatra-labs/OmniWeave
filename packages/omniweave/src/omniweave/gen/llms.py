def _annotations_used() -> tuple[str, ...]:
    """Every annotation spelling reachable from an Action with an `mcp_name`, sorted."""
    seen = {
        str(field.type)
        for spec in ACTIONS.values()
        if spec.mcp_name is not None
        for field in fields(spec.inp)
    }
    return tuple(sorted(seen))


def _manifest_failures() -> tuple[str, ...]:
    """Every reason a block could not be rendered, or would be rendered wrong. Raised at import.

    Four clauses, and the first two are the LEANN property written as a biconditional. A manifest
    that named a tool the registry does not define would send an agent at nothing; one that omitted
    a tool the registry does define is LEANN's file exactly. Neither is representable once both
    directions are checked, and checking only one is how the defect ships.

    The third clause is the type vocabulary: an annotation with no entry in `TYPES` would otherwise
    reach the file as a Python spelling, and a manifest that published `str | tuple[str, ...]` to
    an agent would be publishing this package's source rather than its wire shape.

    The fourth catches a disagreement no other gate would: a default published in artefact 1's
    `inputSchema` that is not the default `inp` declares. `mcp_tools._published_failures()` already
    binds the property NAMES and their ORDER to `dataclasses.fields`; nothing binds their values,
    and two agent-facing files disagreeing about what `--context` does when omitted is the same
    class of defect one field down.
    """
    findings: list[str] = []
    named = {spec.mcp_name for spec in ACTIONS.values() if spec.mcp_name is not None}
    documented = set(declared())
    findings.extend(
        f"{name}: an Action declares this mcp_name and no block is rendered for it"
        for name in sorted(named - documented)
    )
    findings.extend(
        f"{name}: a block is rendered and no Action declares this mcp_name"
        for name in sorted(documented - named)
    )
    findings.extend(
        f"{annotation!r}: no entry in TYPES, so no manifest type can be published for it"
        for annotation in _annotations_used()
        if annotation not in TYPES
    )
    for spec in ACTIONS.values():
        if spec.mcp_name is None or spec.mcp_name not in INPUT_SCHEMAS:
            continue
        published = INPUT_SCHEMAS[spec.mcp_name]["properties"]
        for field in fields(spec.inp):
            declared_default = None if field.default is MISSING else field.default
            if "default" not in published.get(field.name, {}):
                continue
            if published[field.name]["default"] != declared_default:
                findings.append(
                    f"{spec.mcp_name}.{field.name}: inputSchema publishes default "
                    f"{published[field.name]['default']!r} and {spec.inp.__name__} declares "
                    f"{declared_default!r}"
                )
    return tuple(findings)


