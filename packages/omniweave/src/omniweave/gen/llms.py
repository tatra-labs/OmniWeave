def _wrapped(text: str) -> list[str]:
    """One logical line, wrapped at `WIDTH` with LEANN's two-space continuation.

    Splits on a single space and keeps empty tokens, so a run of spaces used for alignment survives
    the round trip. A break is never taken before an empty token, which would otherwise open a
    continuation line with a space and change what the two-space rule means.
    """
    tokens = text.split(" ")
    lines: list[str] = []
    current = tokens[0]
    for token in tokens[1:]:
        candidate = f"{current} {token}"
        if token and len(candidate) > WIDTH and current.strip():
            lines.append(current)
            current = f"  {token}"
        else:
            current = candidate
    lines.append(current)
    return lines


def _entry(key: str, value: str) -> list[str]:
    """`key: value`, wrapped."""
    return _wrapped(f"{key}: {value}")


def _literal(value: object) -> str:
    """A default, in the manifest's spelling. `bool` before `int`, because `bool` IS an `int`."""
    if isinstance(value, bool):
        return _TRUE_FALSE[value]
    return str(value)


def _bounds(published: Mapping[str, Any]) -> list[str]:
    """The published bounds of one property, in 10:2477-2513's order.

    `oneOf` is walked as well as the property itself: `ref` and `source` publish `maxItems` on
    their array branch, and a reader of this file needs the 64 and the 256 as much as an MCP client
    does. Nothing here reads a bound from `surface/inputs.py` directly -- artefact 1 already binds
    every one of them, and a second import would be a second opinion.
    """
    facts: list[str] = []
    for branch in (published, *published.get("oneOf", ())):
        if "minimum" in branch:
            facts.append(f"min={branch['minimum']}")
        if "maximum" in branch:
            facts.append(f"max={branch['maximum']}")
        if "maxLength" in branch:
            facts.append(f"max_length={branch['maxLength']}")
        if "maxItems" in branch:
            facts.append(f"max_items={branch['maxItems']}")
    if "enum" in published:
        facts.append("enum=" + "|".join(str(choice) for choice in published["enum"]))
    return facts


def _input_line(key: str, annotation: str, *, required: bool, default: object) -> str:
    """The mechanical half of an input line: type, arity, default. True of all nine tools."""
    parts = [TYPES[annotation], "required" if required else "optional"]
    if default is not None:
        parts.append(f"default={_literal(default)}")
    return f"{key}: {', '.join(parts)}"


def _tail(published: Mapping[str, Any]) -> str:
    """The published half: bounds, then the schema's own description. Carries its own separators.

    The description is artefact 1's string and not a second transcription, which is the whole
    argument of this module one field down. 10:2497's `ref_forms` key is the sharpest case: it
    prints `d7#412 | e118 | c7 | k22 | ...` while 18:1334's `ref` description prints
    `'d7#412' | 'handbook:d7#412' | ...` -- two agent-facing grammars for one parameter, disagreeing
    on the day they land. This file publishes the one the tool schema publishes. D330.
    """
    tail = "".join(f", {fact}" for fact in _bounds(published))
    description = str(published.get("description", "")).replace("\n", " ").strip()
    return f"{tail} — {description}" if description else tail


def _field_lines(spec: ActionSpec, prefix: str) -> list[str]:
    """Every input field of one Action, published in `dataclasses.fields` order.

    Declaration order and not sorted order, and that is 10:226's rule rather than an exception to
    10:224's: *"schema properties in declaration order (which is `dataclasses.fields` order, itself
    stable)"*. A dataclass's field order is a total order the source fixes; a set's is not.
    """
    published = INPUT_SCHEMAS.get(spec.mcp_name or "", {}).get("properties", {})
    lines: list[str] = []
    for field in fields(spec.inp):
        required = field.default is MISSING and field.default_factory is MISSING
        default = None if field.default is MISSING else field.default
        line = _input_line(
            f"{prefix}.input.{field.name}",
            str(field.type),
            required=required,
            default=default,
        )
        here = published.get(field.name, {})
        lines.extend(_wrapped(line + _tail(here)))
        for nested, shape in here.get("properties", {}).items():
            key = f"{prefix}.input.{field.name}.{nested}"
            lines.extend(_wrapped(f"{key}: {shape['type']}, optional" + _tail(shape)))
    return lines


def _output_line(spec: ActionSpec, prefix: str) -> list[str]:
    """The tool's output: a `$ref`, the packed-prose contract, or the type with neither.

    Three cases and no fourth. 18:1315 makes the split a measurement rather than a taste -- a
    declared `outputSchema` obliges conforming structured content, which in hosts that also emit
    the serialized-JSON text block doubles a 22,000-character answer -- so the two retrievers
    declare none and say what they return instead.
    """
    name = spec.mcp_name or ""
    if name in OUTPUT_SCHEMAS:
        return _entry(f"{prefix}.output", OUTPUT_SCHEMAS[name])
    if spec.out.__name__ == "Answer":
        return _entry(
            f"{prefix}.output",
            f"text/markdown, one content block, <= {HARD_CEILING} chars, no outputSchema",
        )
    return _entry(f"{prefix}.output", f"{spec.out.__name__}, no outputSchema declared")


def tool_block(spec: ActionSpec) -> list[str]:
    """One tool's whole block. Ten-ish lines, every one of them derived from a field.

    `action` is first and it is not decoration: 10:790 has both environment variables accept *"the
    bare Action name (`route.explain`) and the MCP name (`ow_route_explain`)"*, so an agent reading
    this file to widen a listing needs the pair, and the manifest is the only place it appears.
    """
    prefix = f"mcp.tool.{spec.mcp_name}"
    #  `none` for a tool no profile lists -- the header's "DISPATCHABLE when enabled, listed or not"
    #  is the rest of that sentence. An empty value left `listed_in: ` with a trailing space (D473).
    profiles = ", ".join(sorted(spec.listed_in)) or "none"
    lines = [
        *_entry(f"{prefix}.action", spec.name),
        *_entry(f"{prefix}.description", spec.summary),
        *_entry(f"{prefix}.decision", spec.decision),
        *_entry(f"{prefix}.listed_in", profiles),
        *_entry(f"{prefix}.state_changing", _literal(not spec.read_only)),
        *_entry(f"{prefix}.cost_class", spec.cost_class.value),
    ]
    if spec.advanced:
        lines.extend(_entry(f"{prefix}.advanced", ", ".join(sorted(spec.advanced))))
    lines.extend(_field_lines(spec, prefix))
    lines.extend(_output_line(spec, prefix))
    note = TOOL_NOTES.get(spec.mcp_name or "")
    if note is not None:
        deadline = KEYS["serve.add_deadline_ms"].default
        lines.extend(_entry(f"{prefix}.note", note.format(add_deadline_ms=deadline)))
    return lines


def _usage(flag: Flag) -> str:
    """One published argument as a usage word: a bare metavar, or the option with its values.

    An option's values come from `choices` where the CLI publishes a closed set and from `metavar`
    otherwise, which is 10:2520's own form -- `--render text|json|jsonl|rows` beside
    `--corpus <name>`. A switch takes neither and prints as its spelling alone.
    """
    spelling = flag.spelling[0]
    if not spelling.startswith("-"):
        word = (flag.metavar or spelling).upper()
        return f"{word}..." if flag.nargs == "+" else word
    if flag.choices:
        return f"[{spelling} {'|'.join(flag.choices)}]"
    if flag.metavar:
        return f"[{spelling} {flag.metavar}]"
    return f"[{spelling}]"


def _cli_lines() -> list[str]:
    """The CLI block: the global flags, one line per published command, the groups, the codes.

    Keyed by the command's WORDS and not by Action name, because `ow corpora` dispatches two
    Actions -- `corpora` and `corpus.coverage`, whose CLI twin is a flag VALUE on the first
    (10:1424, D299) -- and a manifest that printed two `cli.*` lines spelling the same command
    would be publishing the registry's shape instead of the shell's.
    """
    lines = list(_entry("cli.global", " ".join(_usage(flag) for flag in GLOBAL_FLAGS)))
    for words, actions, _help, flags in commands():
        spelled = " ".join(_usage(flag) for flag in flags)
        key = ".".join(words)
        lines.extend(_entry(f"cli.{key}", " ".join(("ow", *words, spelled)).rstrip()))
        lines.extend(_entry(f"cli.{key}.actions", ", ".join(actions)))
    lines.extend(_entry("cli.groups", " ".join(sorted(CLI_ROSTER))))
    lines.extend(
        _entry(
            "cli.exit_codes",
            " · ".join(f"{row.code} {row.slug}" for row in EXIT_CODES),
        )
    )
    return lines


