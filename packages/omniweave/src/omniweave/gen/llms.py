def render() -> bytes:
    """`llms.txt`, whole. Pure: `ACTIONS`, the two schema tables, the config registry, constants.

    10:232 fixes the encoding -- *"Output is `\\n`-terminated UTF-8 with no BOM"* -- and the final
    newline is added here rather than carried by the last section, so no section has to remember it.
    """
    listed_env = KEYS["serve.listed"].env
    enabled_key = KEYS["serve.enabled"]
    lines: list[str] = [
        f"# llms.txt — {PRODUCT}. GENERATED by `ow surface emit` from omniweave.surface.registry.",
        "# Byte-diff gated (G25). Do not edit: `ow surface emit --check` fails on a hand edit.",
        f"product: {PRODUCT}",
        f"version: {RELEASE}",
        f"homepage: {HOMEPAGE}",
        f"contact: {CONTACT}",
        f"generated_from: omniweave.surface.registry.ACTIONS @ release {RELEASE}",
        f"license: {LICENCE}",
        "",
        "# What it is",
        *_entry("summary", SUMMARY),
        "",
        "# Installation",
        *(line for key, value in INSTALL for line in _entry(key, value)),
        "",
        "# MCP Server Entry Point",
        *(line for key, value in SERVER for line in _entry(key, value)),
        *_entry(
            "mcp.instructions",
            f"delivered on `initialize`, <= {SV2_MAX_CHARS} chars, generated, "
            "bound to the live catalog",
        ),
        "",
        "# Listing model — READ THIS BEFORE ASSUMING A TOOL DOES NOT EXIST",
        *_entry("mcp.profiles", ", ".join(PROFILES)),
        *(
            line
            for profile in PROFILES
            for line in _entry(
                f"mcp.profile.{profile}",
                ", ".join(sorted(str(ACTIONS[name].mcp_name) for name in listed(profile))),
            )
        ),
        *_entry(
            "mcp.listed_note",
            LISTED_NOTE.format(listed=listed_env, enabled=enabled_key.env),
        ),
        *_entry("mcp.enabled_default", str(enabled_key.default)),
        *_entry("mcp.human_only", ", ".join(sorted(HUMAN_ONLY))),
        *_entry("mcp.human_only_note", HUMAN_ONLY_NOTE),
        "",
        "# Tools — every Action with an MCP name. `listed_in` says which profiles LIST it;",
        "# every one of them is DISPATCHABLE when enabled, listed or not.",
        *_entry("mcp.tools", ", ".join(declared())),
    ]
    if unbounded():
        lines.extend(
            _entry(
                "mcp.tools.unbounded",
                ", ".join(unbounded())
                + " — no inputSchema is published for these yet, so their input lines "
                "carry a type and no bounds",
            )
        )
    by_mcp_name = {spec.mcp_name: spec for spec in ACTIONS.values() if spec.mcp_name is not None}
    for name in declared():
        lines.append("")
        lines.extend(tool_block(by_mcp_name[name]))
    lines.extend(
        [
            "",
            f"# CLI ({CLI_NOTE})",
            *_cli_lines(),
            "",
            "# Skills (the OUT direction)",
            *(line for key, value in SKILLS for line in _entry(key, value)),
            "",
            "# How to read a response",
            *(line for name, gloss in VERDICTS for line in _entry(f"verdict.{name}", gloss)),
            *(line for key, value in QUOTE_TIERS for line in _entry(key, value)),
            *(line for key, value in CITE_RULES for line in _entry(key, value)),
            *_entry(
                "answer.sections",
                " ".join(SECTION_MARKERS) + f"   — {SECTION_NOTE}",
            ),
            "",
            "# Notes",
            *(line for note in NOTES for line in _entry("note", note)),
            "",
            "# Lifecycle examples",
            *(line for key, value in EXAMPLES for line in _entry(key, value)),
        ]
    )
    return ("\n".join(lines) + "\n").encode("utf-8")
