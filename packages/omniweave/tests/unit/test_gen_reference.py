"""`omniweave.gen.reference` and `ow surface emit --docs`: section 1.8's eighth output. **D990.**

11-repo-layout.md section 1.8: *"`docs/reference/**` is generated by `ow surface emit --docs` and
byte-diff checked by the `[[job_assertion]]` `gates.reference_docs`, **not** by G25 -- G25's set is
the seven agent-facing artefacts the charter fixes, and `docs/reference/` is an eighth output for
humans."* The step was guarded with a NOT ENFORCED line until the renderer existed.

Three properties carry the weight, and each has a case here: the documents come from the
registers rather than from prose, two renders of one commit are identical, and a file committed
into the directory that no renderer produces is a finding -- the last because a byte-diff over a
tree that ignored strays would pass a directory with a hand-written page in it.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path
from typing import Final

from omniweave.gen import cli_tree, emit, reference, verb
from omniweave.surface import registry

REPO: Final = Path(__file__).resolve().parents[4]
DIRECTORY: Final = REPO / "docs" / "reference"


def test_three_documents_one_per_source_section_1_8_names() -> None:
    """Ruling 1: the verb tree, the SDK surface, codes.toml rendered."""
    assert sorted(reference.DOCUMENTS) == ["cli.md", "codes.md", "sdk.md"]


def test_every_document_is_committed_and_matches_the_render() -> None:
    """What the assertion runs, as a test: `check_docs()` is clean on this tree."""
    assert emit.check_docs() == []


def test_two_renders_of_one_commit_are_identical() -> None:
    """Ruling 3: a generated document that moved between runs would make its own gate useless."""
    assert reference.render_docs() == reference.render_docs()


def test_every_document_names_what_it_is_generated_from_and_the_command() -> None:
    """Ruling 4, and 11:486's rule for every generated file in the tree."""
    for name, payload in reference.render_docs().items():
        text = payload.decode("utf-8")
        assert text.startswith("# "), name
        assert "**GENERATED** by `ow surface emit --docs`" in text, name
        assert "gates.reference_docs" in text, name
        assert "Generated from " in text, name
        assert text.endswith("\n") or text.endswith("|"), name


def test_the_cli_document_carries_every_command_the_tree_has() -> None:
    """Ruling 2: the same `commands()` the argparse tree is built from, so it cannot describe a
    CLI that does not exist."""
    text = reference.cli_md().decode("utf-8")
    for words, _actions, _summary, _flags in cli_tree.commands():
        assert f"## `ow {' '.join(words)}`" in text, words
    assert text.count("\n## ") == len(cli_tree.commands())


def test_the_sdk_document_carries_every_action_and_its_input_fields() -> None:
    text = reference.sdk_md().decode("utf-8")
    for name in registry.ACTIONS:
        assert f"## `{name}`" in text, name
    #  `add` is the shape that would break a markdown table unescaped: `str | tuple[str, ...]`.
    assert "| `source` | `str \\| tuple[str, ...]` |" in text


_DIVIDER: Final = re.compile(r"(?<!\\)\|")
"""An UNESCAPED pipe, which is the only kind that divides a markdown cell. A flag's help can
contain a pipe of its own -- `ow open`'s `ref` lists five address shapes separated by them -- and
the renderer escapes those; a splitter that did not know the difference would read one row as
seven cells and call the escaping broken."""


def test_every_table_row_has_its_headers_cell_count() -> None:
    """A union type ends the cell it sits in unless it is escaped, and the symptom is a row with
    more cells than its header. This counts them rather than trusting the escape."""
    for name, payload in reference.render_docs().items():
        width = 0
        for number, line in enumerate(payload.decode("utf-8").splitlines(), 1):
            if not line.startswith("|"):
                width = 0
                continue
            cells = len(_DIVIDER.split(line)) - 2  # the bounding pipes bound, they do not divide
            if not width:
                width = cells
                continue
            assert cells == width, f"{name}:{number} has {cells} cell(s), not {width}: {line!r}"


def test_the_codes_document_renders_every_row_of_the_register() -> None:
    rows = tomllib.loads((REPO / "codes.toml").read_text(encoding="utf-8"))["code"]
    text = reference.codes_md().decode("utf-8")
    assert f"## Codes ({len(rows)})" in text
    for row in rows:
        assert f"### `{row['numeric']}` -- `{row['symbol']}`" in text, row["numeric"]


def test_a_stray_file_in_the_directory_is_a_finding() -> None:
    """Ruling 5. Written and removed here rather than mocked, because the clause is about the
    real directory and a mock would assert the mock."""
    stray = DIRECTORY / "hand-written.md"
    assert not stray.exists(), "a previous run left this behind"
    stray.write_text("a page nobody generates\n", encoding="utf-8")
    try:
        findings = emit.check_docs()
        assert findings == ["docs/reference/hand-written.md: committed and generated by nothing"]
    finally:
        stray.unlink()
    assert emit.check_docs() == []


def test_a_hand_edit_is_a_finding_and_an_emit_repairs_it() -> None:
    """The gate's own purpose, exercised against the committed tree and put back."""
    where = DIRECTORY / "cli.md"
    before = where.read_bytes()
    where.write_bytes(before + b"\nhand-edited\n")
    try:
        assert emit.check_docs() == ["docs/reference/cli.md: differs from the registry's render"]
        assert emit.emit_docs() == ("docs/reference/cli.md",)
        assert emit.check_docs() == []
    finally:
        where.write_bytes(before)
    assert where.read_bytes() == before


def test_the_verb_reports_both_halves() -> None:
    clean = verb.run(check=True, bless=False, docs=True)
    assert clean.exit_code == verb.OK
    assert clean.lines == ("surface emit --docs --check: docs/reference matches the registry",)
    written = verb.run(check=False, bless=False, docs=True)
    assert written.exit_code == verb.OK
    assert written.lines[-1] == "surface emit --docs: 0 document(s) changed", (
        "an emit over an up-to-date tree writes nothing, so a re-run is not a diff"
    )


def test_docs_and_the_seven_are_separate_output_sets() -> None:
    """Section 1.8 again: this is an EIGHTH output, so `--docs` must not touch G25's set and a
    plain emit must not touch the reference tree."""
    assert "docs/reference" not in str(emit.ARTEFACTS), "the eighth is not in the seven"
    assert emit.check() == (), "G25 is clean independently of the reference tree"


def test_the_workflow_step_runs_the_verb_unguarded() -> None:
    """The step was a NOT ENFORCED echo behind a directory test until the renderer landed."""
    text = (REPO / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8")
    assert "run: uv run ow surface emit --docs --check" in text
    assert "gates.reference_docs NOT ENFORCED" not in text
