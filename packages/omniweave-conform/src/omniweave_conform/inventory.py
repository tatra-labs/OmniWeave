"""The test inventory: per-area test and property counts, read off a collection. **D845, D846.**

13-quality.md:1829 defines Q-G24 over `eval/inventory.toml`: *"per-area unit and property counts --
byte-matches `pytest --collect-only -q`"*, and a net decrease in any area fails without a
`BLESS.log` row. D845 built this in `tools/gate_inventory.py`. D846 moves the counting here,
because `ow eval bless --inventory` regenerates the same file across the `omniweave.eval` entry
point, and an entry point cannot import `tools/`. The gate keeps the judging: the byte diff and
the decrease against a base.

- `collect()` runs the collection in a fresh interpreter with a recording plugin.
- `areas()` counts what it recorded.
- `render()` and `parse()` write and read the file.
- `decreases()` names what fell.
- `bless_inventory()` is `ow eval bless --inventory`: it rewrites the file and appends the
  `BLESS.log` row a decrease needs (D846).

## Rulings (D845's, moved)

1. **An area is a distribution and the directory under its `tests/`**, e.g. `omniweave-core/unit`.
   A file directly in `tests/` is in `<dist>/tests`. A `conftest.py` governs a directory, so a
   directory is the coarsest grain at which a lost conftest still shows.
2. **A unit is a collected item, and a property is one hypothesis drives,** read with
   `hypothesis.is_hypothesis_test`. Every tier is collected: collecting runs nothing, and a tier
   left out could shrink unseen.
3. **Collection runs in a fresh interpreter**, through `omniweave_core.host.subproc.run_captured`,
   with a plugin written into a scratch directory. The environment is an argument: library code
   reads no ambient state.
4. **The file is one `[[area]]` per area, sorted, with `tests` and `properties` and no total**,
   LF and with no timestamps.

Specified in 13-quality.md sections 2.1, 13.1 and 13.3.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
import tomllib
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Final

from omniweave_core.errors import QualityError
from omniweave_core.host.subproc import run_captured

from omniweave_conform.bless import BlessRow, parse_log

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

__all__ = [
    "HEADER",
    "INVENTORY",
    "LOG",
    "PLUGIN",
    "Blessed",
    "Collection",
    "Count",
    "area_of",
    "areas",
    "bless_inventory",
    "collect",
    "decreases",
    "parse",
    "render",
]

INVENTORY: Final = "eval/inventory.toml"
HEADER: Final = (
    "# eval/inventory.toml -- GENERATED by `uv run tools/gate_inventory.py --write` from\n"
    "# `pytest --collect-only`; do not edit. Q-G24 byte-diffs it, and a net decrease in any\n"
    "# area fails without a BLESS.log row (13-quality.md:1829). Per area: collected tests, and\n"
    "# how many of them hypothesis drives.\n"
)
PLUGIN: Final = '''"""Q-G24's recorder: each collected node id, and whether hypothesis drives it."""

import json
import os


def pytest_collection_finish(session):
    try:
        from hypothesis import is_hypothesis_test
    except ImportError:
        def is_hypothesis_test(_function):
            return False
    rows = []
    for item in session.items:
        function = getattr(item, "obj", None)
        rows.append([item.nodeid, bool(function is not None and is_hypothesis_test(function))])
    with open(os.environ["OW_INVENTORY_OUT"], "w", encoding="utf-8") as sink:
        json.dump(rows, sink)
'''
"""Ruling 3's plugin, written into a scratch directory as `ow_inventory_plugin.py`."""
COLLECT_TIMEOUT_S: Final = 900.0
_TAIL: Final = 15


@dataclass(frozen=True, slots=True)
class Count:
    """One area's units and properties."""

    tests: int
    properties: int


@dataclass(frozen=True, slots=True)
class Collection:
    """What a collection produced: pytest's exit code, the items, and the output's tail."""

    code: int | None
    rows: tuple[tuple[str, bool], ...]
    tail: tuple[str, ...]


def area_of(nodeid: str) -> str:
    """Ruling 1: `packages/<dist>/tests/<dir>/...` is `<dist>/<dir>`; a top file, `<dist>/tests`."""
    parts = nodeid.split("::", 1)[0].split("/")
    if len(parts) > 3 and parts[0] == "packages" and parts[2] == "tests":  # noqa: PLR2004
        return f"{parts[1]}/{parts[3] if len(parts) > 4 else 'tests'}"  # noqa: PLR2004
    return parts[0] if len(parts) > 1 else "(root)"


def areas(rows: Sequence[tuple[str, bool]]) -> dict[str, Count]:
    """Ruling 2: `(node id, is a property)` pairs counted per area."""
    tests: dict[str, int] = {}
    properties: dict[str, int] = {}
    for nodeid, is_property in rows:
        area = area_of(nodeid)
        tests[area] = tests.get(area, 0) + 1
        properties[area] = properties.get(area, 0) + int(is_property)
    return {area: Count(tests[area], properties[area]) for area in sorted(tests)}


def render(counted: Mapping[str, Count]) -> str:
    """Ruling 4: the inventory's bytes."""
    lines = [HEADER.rstrip("\n")]
    for area in sorted(counted):
        count = counted[area]
        lines += ["", "[[area]]", f"area = {json.dumps(area)}"]
        lines += [f"tests = {count.tests}", f"properties = {count.properties}"]
    return "\n".join(lines) + "\n"


def parse(text: str) -> dict[str, Count]:
    """An inventory's areas, or `ValueError` for one that is not ruling 4's shape."""
    try:
        doc = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        message = f"{INVENTORY} does not parse: {exc}"
        raise ValueError(message) from exc
    out = {}
    for row in doc.get("area", []):
        if not isinstance(row, dict) or set(row) != {"area", "tests", "properties"}:
            message = f"{INVENTORY}: an [[area]] row is not area, tests and properties"
            raise ValueError(message)
        out[str(row["area"])] = Count(int(row["tests"]), int(row["properties"]))
    return out


def decreases(before: Mapping[str, Count], after: Mapping[str, Count]) -> list[str]:
    """Each area that lost tests or properties, or vanished, as a line."""
    out = []
    for area in sorted(before):
        was, now = before[area], after.get(area, Count(0, 0))
        if area not in after:
            out.append(f"{area}: gone, with its {was.tests} test(s)")
            continue
        if now.tests < was.tests:
            out.append(f"{area}: tests {was.tests} -> {now.tests}")
        if now.properties < was.properties:
            out.append(f"{area}: properties {was.properties} -> {now.properties}")
    return out


def collect(root: Path, env: Mapping[str, str]) -> Collection:
    """Ruling 3: collect `root`'s tests in a fresh interpreter under `env`."""
    with tempfile.TemporaryDirectory(prefix="ow-inventory-") as scratch:
        folder = Path(scratch)
        (folder / "ow_inventory_plugin.py").write_bytes(PLUGIN.encode("utf-8"))
        out = folder / "items.json"
        child = dict(env)
        child["OW_INVENTORY_OUT"] = str(out)
        child["PYTHONPATH"] = os.pathsep.join(
            p for p in (scratch, child.get("PYTHONPATH", "")) if p
        )
        argv = (
            sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider",
            "-p", "ow_inventory_plugin",
        )  # fmt: skip
        done = run_captured(argv, stdin=b"", cwd=str(root), env=child, timeout_s=COLLECT_TIMEOUT_S)
        rows = json.loads(out.read_text(encoding="utf-8")) if out.is_file() else []
    text = (done.stdout + done.stderr).decode("utf-8", "replace")
    tail = tuple(text.splitlines()[-_TAIL:]) or ((done.failed,) if done.failed else ())
    return Collection(
        done.returncode, tuple((str(nodeid), bool(prop)) for nodeid, prop in rows), tail
    )


LOG: Final = "eval/BLESS.log"


@dataclass(frozen=True, slots=True)
class Blessed:
    """What `bless_inventory()` wrote: the row, the areas that fell, and every area that moved."""

    row: str
    fell: tuple[str, ...]
    changed: tuple[str, ...]
    tests: int


def bless_inventory(
    root: Path, *, reason: str, date: str, author: str, env: Mapping[str, str]
) -> Blessed:
    """`ow eval bless --inventory` (13:1847, :1872): rewrite the inventory and append its row. D846.

    - The collection must exit 0. A row may not bless a count a failed collection produced.
    - Something must have fallen. A count that only grew needs no bless, and
      `gate_inventory.py --write` takes it.
    - The row's glob is `eval/inventory.toml`. Each area that fell is `structural`, and each other
      area that moved is `incidental`. Nothing is `unexplained`: a collection explains its own
      count.
    - The reason, date and author are held to `BlessRow`'s grammar before anything is written.
      Then the inventory is written, and the row is appended to `eval/BLESS.log`, which must
      already be append-only well formed.
    """
    done = collect(root, env)
    if done.code != 0:
        raise QualityError(
            f"the collection exited {done.code}, so its count is not one a row may bless: "
            + (done.tail[-1] if done.tail else "no output"),
            fix="fix what stops the collection, then run ow eval bless again",
        )
    after = areas(done.rows)
    target = root / INVENTORY
    before = parse(target.read_text(encoding="utf-8")) if target.is_file() else {}
    fell = decreases(before, after)
    if not fell:
        raise QualityError(
            "nothing to bless: no area's tests or properties fell",
            fix="a count that only grew needs no row: uv run tools/gate_inventory.py --write",
        )
    fallen = {line.split(":", 1)[0] for line in fell}
    changed = sorted(a for a in set(before) | set(after) if before.get(a) != after.get(a))
    counts = {
        "incidental": len([a for a in changed if a not in fallen]),
        "structural": len(fallen),
        "unexplained": 0,
    }
    row = BlessRow(date=date, author=author, glob=INVENTORY, counts=counts, reason=reason)
    log = root / LOG
    old = log.read_text(encoding="utf-8") if log.is_file() else ""
    parse_log(old)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(render(after).encode("utf-8"))
    log.write_bytes((old + row.line()).encode("utf-8"))
    return Blessed(
        row.line().rstrip("\n"),
        tuple(fell),
        tuple(changed),
        sum(count.tests for count in after.values()),
    )
