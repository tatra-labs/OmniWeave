"""The retrieve suite's self-verifying half: every cite an Answer renders, resolved. D870.

13-quality.md:1094 and :1101 make two of the retrieve suite's rows **self-verifying**, so they need
no labels and no model:
- `citability_violations`, hard at **0**, *"a **count**, not a rate: rendered Answers containing a
  `cite` that does not resolve"*;
- `citation_soundness`, a floor at 0.995: *"over every `cite` emitted in a scored run, the fraction
  resolving to a Block, a page and either a `Quad` or a `Locus.reason`, **and** whose `byte_exact`
  bit, where set, re-grounds under `normalize_k`"*.

This module asks questions of real stores and checks every cite the rendered Answers carry.

## Rulings

1. **The questions are the adoption catalogue's**, `bench/serve/tasks.toml` (13 section 8.8,
   ADR-14 D14.2), every task but the `damaged` ones, which need a damaged corpus of their own and
   are the absence suite's business. The corpora are the ones the catalogue names, generated by
   `fixtures/gen/gen_reference_corpora.py` at `quick` scale and built through a real `ow add`, each
   in its own project, as `absence.build()` builds one.
2. **An Answer is what `ow query` renders**: one read-only `execute()`, `answer.pack()` with the
   corpus's name, and `answer.render()`. Its cites are every block header the render kept
   (`render.cites_of()`) and every cite an `ow:notseen` or `ow:sent-earlier` pointer names, because
   a pointer's cite is one a reader will follow too.
3. **A cite is sound when it resolves**: a live block of the head generation carries it, and
   `store.doc.locate_block()` places that block on a page with a `Quad` or a `Locus.reason`
   (INV-9 makes one of the two certain once the block is found). A cite whose `byte_exact` bit is
   set is **not** sound in this build: nothing here re-grounds under `normalize_k`, and
   `retrieve.execute.byte_exact()` sets the bit on no block this build stores, so the clause holds
   vacuously and is never claimed.
4. **A violation is an Answer**: an Answer with at least one cite that does not resolve counts
   once, as 13:1094 counts it. The artefact half of that row, OUT11's restricted items, is the out
   path's and is named as not measured.
"""

from __future__ import annotations

import tomllib
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from typing import TYPE_CHECKING, Final

from omniweave_conform.absence import build, generator

if TYPE_CHECKING:
    from collections.abc import Callable, Mapping, Sequence
    from pathlib import Path

    from omniweave_core.answer.render import Answer

__all__ = ["CATALOG", "Asked", "Checked", "Task", "ask", "check", "load_tasks", "run_suite"]

CATALOG: Final = "bench/serve/tasks.toml"
"""Ruling 1: the adoption catalogue, relative to the checkout's root."""

SKIPPED_CLASS: Final = "damaged"


@dataclass(frozen=True, slots=True)
class Task:
    """One catalogue question: its id, its corpus, and what it asks."""

    task_id: str
    corpus: str
    prompt: str


@dataclass(frozen=True, slots=True)
class Asked:
    """One rendered Answer's cites, and which of them did not resolve."""

    task_id: str
    cites: tuple[str, ...]
    unsound: tuple[str, ...]

    @property
    def violates(self) -> bool:
        return bool(self.unsound)


@dataclass(frozen=True, slots=True)
class Checked:
    """The suite's run: every Answer asked, and the documents its corpora were built from."""

    asked: tuple[Asked, ...]
    documents: Mapping[str, bytes]
    skipped: int

    @property
    def violations(self) -> int:
        return sum(1 for one in self.asked if one.violates)

    @property
    def cites(self) -> int:
        return sum(len(one.cites) for one in self.asked)

    @property
    def sound(self) -> int:
        return self.cites - sum(len(one.unsound) for one in self.asked)


def load_tasks(root: Path) -> tuple[tuple[Task, ...], int]:
    """The catalogue's tasks this suite asks, and how many `damaged` ones it leaves (ruling 1)."""
    path = root / CATALOG
    if not path.is_file():
        msg = f"no adoption catalogue at {path}"
        raise RuntimeError(msg)
    rows = tomllib.loads(path.read_text(encoding="utf-8")).get("task", [])
    asked = tuple(
        Task(str(row["id"]), str(row["corpus"]), str(row["prompt"]))
        for row in rows
        if row.get("class") != SKIPPED_CLASS
    )
    return asked, sum(1 for row in rows if row.get("class") == SKIPPED_CLASS)


def ask(work: Path, task: Task, *, now_ns: Callable[[], int]) -> Asked:
    """One Answer, rendered as `ow query` renders it, and its cites checked (rulings 2-4)."""
    from omniweave_core.answer.pack import pack  # noqa: PLC0415
    from omniweave_core.answer.render import cites_of, render  # noqa: PLC0415
    from omniweave_core.retrieve.execute import execute  # noqa: PLC0415
    from omniweave_core.retrieve.types import Query, RetrievalPolicy  # noqa: PLC0415
    from omniweave_core.store import reader as store_reader  # noqa: PLC0415
    from omniweave_core.store import sqlite as store_sqlite  # noqa: PLC0415

    connection = store_sqlite.connect_readonly(work / "project" / ".omniweave" / "docs.owstore")
    try:
        reader = store_reader.SqliteReader(connection, now_ns=now_ns())
        retrieval = execute(reader, Query(text=task.prompt), RetrievalPolicy())
        packed = pack(retrieval, corpus="docs")
        document = render(packed.answer, max_chars=packed.max_chars)
        cites = _cites(packed.answer, cites_of(document))
        unsound = tuple(cite for cite in cites if not check(connection, cite, packed.answer))
    finally:
        connection.close()
    return Asked(task.task_id, cites, unsound)


def check(connection: object, cite: str, answer: Answer) -> bool:
    """Ruling 3: does `cite` resolve to a placed, live block, with no unproved exactness?"""
    from omniweave_core.store.doc import locate_block  # noqa: PLC0415

    exact = any(block.byte_exact for block in answer.evidence if block.cite == cite)
    if exact:
        return False
    row = connection.execute(  # type: ignore[attr-defined]
        "SELECT block_id FROM ow_block_head WHERE cite = ?", (cite,)
    ).fetchone()
    if row is None:
        return False
    locus = locate_block(connection, int(row[0]))  # type: ignore[arg-type]
    return locus is not None and (locus.quad is not None or bool(locus.reason))


def _cites(answer: Answer, rendered: Sequence[str]) -> tuple[str, ...]:
    """Ruling 2: the rendered headers' cites, then every pointer's, each once, in order."""
    pointed = [cite for pointer in (*answer.pointers, *answer.withheld) for cite in pointer.cites]
    return tuple(dict.fromkeys((*rendered, *pointed)))


def run_suite(root: Path, *, work: Path, now_ns: Callable[[], int], workers: int = 3) -> Checked:
    """Every catalogue corpus built once, then every task asked of its own corpus (ruling 1)."""
    tasks, skipped = load_tasks(root)
    corpora = list(dict.fromkeys(task.corpus for task in tasks))
    documents = {
        corpus: {doc.path: doc.to_bytes() for doc in generator(root).documents(corpus, "quick")}
        for corpus in corpora
    }
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        for future in [pool.submit(build, work / corpus, documents[corpus]) for corpus in corpora]:
            future.result()
    asked = tuple(ask(work / task.corpus, task, now_ns=now_ns) for task in tasks)
    read = {
        f"{corpus}/{path}": data
        for corpus, docs in documents.items()
        for path, data in docs.items()
    }
    return Checked(asked=asked, documents=read, skipped=skipped)
