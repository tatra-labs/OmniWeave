"""The roundtrip suite: law R2 over each target's golden, one verdict per addressed element. D871.

13-quality.md:1564 gives R2, *address survival*, its evaluation obligation: *"for every IL element
carrying `data-ow-el`, exactly one Block with the matching `el`"*, judged by *"the `roundtrip`
assertion type (§8.1): missing, duplicated, kind-mismatched or text-mismatched all fail"*. 13:1011
defines that type: *"after `compile` then `read_back`, exactly one Block carries
`x["x.ow.el"] == e.el` with the expected kind and NFC-equal text"*. The conformance `target` suite
already compiles a golden, reads it back and judges R2 (`suites.target.suite.run_target`, D787);
this module runs it for each target the register names, and states one outcome per element.

## Rulings

1. **A target is a register `[[target]]` row**: its compile card, its `read_back` card, its golden
   fixture and any `config` the compiler is built with. A `config` value under `paths` is resolved
   against the checkout's root, because a driver resolves no path against the working directory
   (`compile.pptx.native`'s `font_dir` refuses a relative one). Both drivers are activated from
   their cards, as `Subject` activates a parse driver, and the construct table loads with the
   target's own normalizers through `host.activate.normalizers()`, the one module allowed to import
   a driver's code.
2. **The elements are `suites.target.suite.addressed()`'s**: every element of the golden IL
   carrying `data-ow-el`, under its construct, which is the population R2 judges. An element passes
   when no R2 failure names it; a failure's kind and detail are its explanation.
3. **An R2 the suite could not judge is not a verdict.** A golden whose gate does not reach
   `lower()` (OUT23), or a target with no reader, leaves R2 `unknown` with the suite's reason, and
   the run says so rather than writing verdicts it does not have.
4. **The golden ships what it needs to be measured.** `fixtures/out/golden/pptx/` names the face
   `Probe Sans`, which `tests/fontkit.py` writes, so its measurement band runs (D805). The face is
   committed under the golden's `fonts/`, generated by that helper with its defaults, and the
   register points `compile.pptx.native`'s `font_dir` at it.
"""

from __future__ import annotations

import hashlib
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final

from omniweave_core.drivers.card import DriverCard, load_card
from omniweave_core.host.activate import code_fingerprint, normalizers
from omniweave_core.out.card import CompileCard
from omniweave_core.out.constructs import ConstructTable
from omniweave_core.out.job import ILBundle

from omniweave_conform.subject import Subject
from omniweave_conform.suites.target.suite import addressed, run_target

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence

__all__ = ["Element", "Judged", "Target", "golden_digest", "judge", "targets"]

LAW: Final = "r2"


@dataclass(frozen=True, slots=True)
class Target:
    """One register `[[target]]` row, its paths resolved (ruling 1)."""

    target: str
    card: Path
    read_back: Path
    golden: Path
    config: Mapping[str, Any]


@dataclass(frozen=True, slots=True)
class Element:
    """One addressed element's outcome under R2 (ruling 2)."""

    el: str
    construct: str
    passed: bool
    explanation: str


@dataclass(frozen=True, slots=True)
class Judged:
    """One target's R2: its compiler's identity, its elements, or why R2 was not judged."""

    target: Target
    driver: str
    version: str
    gate: str
    elements: tuple[Element, ...]
    unknown: str | None
    il_units: tuple[Path, ...]
    fingerprint: str
    """`host.activate.code_fingerprint()` over the compile driver's `*.py`."""


def targets(register: Mapping[str, Any], root: Path) -> tuple[Target, ...]:
    """The register's `[[target]]` rows, every path resolved against `root` (ruling 1)."""
    out = []
    for row in register.get("target", []):
        config = dict(row.get("config", {}))
        config.update({key: str(root / value) for key, value in row.get("paths", {}).items()})
        out.append(
            Target(
                target=str(row["target"]),
                card=root / str(row["card"]),
                read_back=root / str(row["read_back"]),
                golden=root / str(row["golden"]),
                config=config,
            )
        )
    return tuple(out)


def judge(target: Target) -> Judged:
    """Compile the golden, read it back, and state R2 for each addressed element (rulings 1-3)."""
    card = _card(target.card)
    sibling = CompileCard.of(card)
    constructs = ConstructTable.load(
        Path(str(card.source)).parent / sibling.constructs, normalizers(card)
    )
    with tempfile.TemporaryDirectory(prefix="ow-eval-roundtrip-") as scratch:
        work = Path(scratch)
        subject = Subject.of(target.card, workdir=work / "compile")
        fingerprint = code_fingerprint(subject.source_files())
        compiler: Any = subject.instantiate(**target.config)
        reader: Any = Subject.of(target.read_back, workdir=work / "read").instantiate()
        report = run_target(
            compiler, card, constructs, target.golden, workdir=work / "suite", reader=reader
        )
        bundle = ILBundle.load(
            target.golden / "il", carrier=compiler.carrier, constructs=constructs
        )
        elements = addressed(bundle, compiler, constructs)
    units = tuple(sorted(path for path in (target.golden / "il").iterdir() if path.is_file()))
    outcome = report.law(LAW)
    if outcome.status != "checked" or outcome.result is None:
        return Judged(
            target,
            card.identity.id,
            card.identity.version,
            str(report.gate),
            (),
            outcome.reason or f"R2 is {outcome.status}",
            units,
            fingerprint,
        )
    failed: dict[str, list[str]] = {}
    for failure in outcome.result.failures:
        failed.setdefault(str(failure.subject), []).append(f"{failure.kind}: {failure.msg}")
    return Judged(
        target,
        card.identity.id,
        card.identity.version,
        str(report.gate),
        tuple(
            Element(e.el, e.construct, e.el not in failed, "; ".join(failed.get(e.el, ())))
            for e in elements
        ),
        None,
        units,
        fingerprint,
    )


def golden_digest(golden: Path, files: Sequence[Path] | None = None) -> str:
    """The DDL's `sha256 over sorted (relpath, sha256)`, NUL-framed, over the whole golden."""
    chosen = files if files is not None else [p for p in golden.rglob("*") if p.is_file()]
    framed = hashlib.sha256()
    for relpath, digest in sorted(
        (path.relative_to(golden).as_posix(), hashlib.sha256(path.read_bytes()).hexdigest())
        for path in chosen
    ):
        framed.update(relpath.encode("utf-8") + b"\x00" + digest.encode("ascii") + b"\x00")
    return framed.hexdigest()


def _card(path: Path) -> DriverCard:
    card = load_card(path.read_bytes(), origin="driver_path", source=str(path))
    if not isinstance(card, DriverCard):
        msg = f"{path} is not a driver card"
        raise TypeError(msg)
    return card
