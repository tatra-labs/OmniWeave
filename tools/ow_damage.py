@dataclass(frozen=True, slots=True)
class Damaged:
    """One pair's damaged run, and the run after its fix, or why the fix did not run."""

    damaged: Observed
    fixed: Observed | None
    refusal: str | None


def run_pair(
    injector: Injector,
    fixture: Fixture,
    work: Path,
    *,
    documents: Mapping[str, bytes],
    admit_fix: Callable[[Sequence[str]], str | None] = admit,
) -> Damaged:
    """Damage one file, build, read, run the fix, and read again. Needs no pristine run."""
    damaged_docs = dict(documents)
    damaged_docs[fixture.target] = injector.transform(documents[fixture.target])
    build(work, damaged_docs, config=injector.config)
    damaged = ask(work, fixture.question)
    cause = damaged.cause(injector.row.gate)
    refusal: str | None
    argv: tuple[str, ...] = ()
    try:
        argv = split_fix("" if cause is None else cause.fix)
        refusal = admit_fix(argv)
    except FixRefusedError as exc:
        refusal = str(exc)
    if refusal is not None:
        return Damaged(damaged, None, refusal)
    if injector.restores_source:
        (work / "project" / "docs" / fixture.target).write_bytes(documents[fixture.target])
    extra: Mapping[str, str] = {}
    if injector.repair is not None:
        try:
            repair = injector.repair("" if cause is None else cause.detail)
        except FixRefusedError as exc:
            return Damaged(damaged, None, str(exc))
        for relative, text in repair.append.items():
            with (work / "project" / relative).open("a", encoding="utf-8") as handle:
                handle.write(text)
        extra = repair.env
    ran = _ow(work, argv[1:], extra)
    if ran.returncode != 0:
        tail = ran.stderr.decode("utf-8", "replace")[-600:]
        return Damaged(damaged, None, f"the fix exited {ran.returncode} {ran.failed}: {tail}")
    return Damaged(damaged, ask(work, fixture.question), None)


def _pristine(
    work: Path, documents: Mapping[str, bytes], questions: Sequence[str]
) -> list[Observed]:
    build(work, documents)
    return [ask(work, question) for question in questions]


# ---------------------------------------------------------------------------------------------
# The run
# ---------------------------------------------------------------------------------------------


def _row(register: Path) -> Mapping[str, Any] | None:
    if not register.is_file():
        return None
    rows = tomllib.loads(register.read_text(encoding="utf-8")).get("gate", [])
    return next((row for row in rows if row.get("metric") == METRIC), None)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="ow_damage",
        description="The deterministic half of the absence suite: every built Injector, "
        "damaged, read, fixed and read again (13-quality.md section 8.6).",
    )
    parser.add_argument("--deterministic-half", action="store_true", help="the only half built")
    parser.add_argument("--injector", action="append", help="run only these Injectors")
    parser.add_argument("--keep", type=Path, help="keep every fixture project under this folder")
    parser.add_argument("--json", type=Path, help="also write the report as JSON here")
    parser.add_argument(
        "--workers",
        type=int,
        default=min(4, os.cpu_count() or 1),
        help="fixture builds run at once; each is one `ow add` (default: min(4, cores))",
    )
    parser.add_argument("--register", type=Path, default=REGISTER)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Run every built Injector over its fixtures. 0 passed, 1 failed, 2 could not run."""
    args = _parser().parse_args(argv)
    row = _row(args.register)
    if row is None:
        emit(f"ow_damage: {args.register} has no {METRIC} row; the gate has no budget to meet")
        return EXIT_USAGE
    chosen = list(INJECTORS) if not args.injector else list(dict.fromkeys(args.injector))
    unknown = [name for name in chosen if name not in INJECTORS]
    if unknown:
        owed = [one.name for one in TABLE if one.name not in INJECTORS]
        emit(f"ow_damage: {unknown} are not built; built: {list(INJECTORS)}; owed: {owed}")
        return EXIT_USAGE

    root = args.keep or Path(tempfile.mkdtemp(prefix="ow-damage-"))
    emit(
        f"{METRIC}  (hard at {float(row['budget']):.4f} over every (Injector, fixture) pair; "
        f"owner {row.get('owner')}, review by {row.get('review_by')})"
    )
    emit()
    pairs = [
        (INJECTORS[name], index, fixture)
        for name in chosen
        for index, fixture in enumerate(FIXTURES.get(name, ()))
    ]
    results: list[Assessment] = []
    try:
        sets = list(dict.fromkeys((fixture.corpus, fixture.paths) for _i, _n, fixture in pairs))
        documents = {
            key: _documents(next(f for _i, _n, f in pairs if (f.corpus, f.paths) == key))
            for key in sets
        }
        with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
            pristine_runs = {
                key: pool.submit(
                    _pristine,
                    root / f"pristine-{number}",
                    documents[key],
                    [f.question for _i, _n, f in pairs if (f.corpus, f.paths) == key],
                )
                for number, key in enumerate(sets)
            }
            damaged_runs = [
                pool.submit(
                    run_pair,
                    injector,
                    fixture,
                    root / f"{injector.name}-{index}",
                    documents=documents[(fixture.corpus, fixture.paths)],
                )
                for injector, index, fixture in pairs
            ]
            pristine_of = {key: future.result() for key, future in pristine_runs.items()}
            for (injector, _index, fixture), future in zip(pairs, damaged_runs, strict=True):
                key = (fixture.corpus, fixture.paths)
                same_set = [f for _i, _n, f in pairs if (f.corpus, f.paths) == key]
                pristine = pristine_of[key][same_set.index(fixture)]
                run = future.result()
                result = assess(
                    injector,
                    fixture.name,
                    pristine=pristine,
                    damaged=run.damaged,
                    fixed=run.fixed,
                    fix_refusal=run.refusal,
                )
                results.append(result)
                emit(f"  {'ok  ' if result.ok else 'FAIL'}  {injector.name} x {fixture.name}")
                for clause in result.clauses:
                    mark = "ok  " if clause.ok else "FAIL"
                    emit(f"          {mark}  {clause.name}: {clause.why}")
                emit()
    except (RuntimeError, OSError) as exc:
        emit(f"ow_damage: the suite could not run: {type(exc).__name__}: {exc}")
        return EXIT_USAGE
    finally:
        if args.keep is None:
            shutil.rmtree(root, ignore_errors=True)

    passed = sum(1 for result in results if result.ok)
    owed = [one.name for one in TABLE if one.name not in INJECTORS]
    value = passed / len(results) if results else None
    emit(f"  population: {len(INJECTORS)} of {len(TABLE)} Injectors built; owed: {', '.join(owed)}")
    if args.json is not None:
        report = {
            "metric": METRIC,
            "value": value,
            "pairs": [
                {
                    "injector": result.injector,
                    "fixture": result.fixture,
                    "ok": result.ok,
                    "clauses": [{"name": c.name, "ok": c.ok, "why": c.why} for c in result.clauses],
                }
                for result in results
            ],
            "built": list(INJECTORS),
            "owed": owed,
        }
        args.json.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    if value is None:
        emit("ow_damage: no pair ran")
        return EXIT_USAGE
    emit(f"{METRIC} = {value:.4f} over {len(results)} pair(s)")
    return EXIT_OK if passed == len(results) else EXIT_FAIL


if __name__ == "__main__":
    raise SystemExit(main())
