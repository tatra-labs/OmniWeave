"""`ow eval run --suite absence --deterministic-half`: every built Injector over its fixtures.

Q-G7's paired-damage half (13-quality.md section 8.6), and the line of P6's exit criteria it stands
for (16-roadmap.md, section 9):

    uv run ow eval run --suite absence --deterministic-half

**Why a `tools/` script.** `ow eval` is P10's verb group and does not exist, so this is the
standing pattern (ledger D25): the library half is `omniweave_conform.damage` -- the thirteen-row
table, the Injectors built, and `assess()` -- and this file builds fixtures, runs `ow`, reads the
verdicts and prints. It is the one place allowed to import `omniweave`, which the harness needs for
13:1306's *"parses the string against the `ow` Action registry"*.

## One `(Injector, fixture)` pair, four runs

1. **pristine**: the fixture's documents, generated by `fixtures/gen/gen_reference_corpora.py`,
   through a real `ow add`. Shared by every pair over the same documents.
2. **damaged**: the same documents with the Injector applied to one file, built from scratch,
   under `PROJECT` and the Injector's own `config` (`inflate`'s `[ingest] max_parts`, D644).
3. **the fix**: the damaged run's `DegradeCause.fix` for the expected gate, split by
   `damage.split_fix()`, admitted against the registry by `admit()`, and run with no shell. A
   source-bytes Injector restores the file first (D640). `encrypt` restores nothing: its
   `Injector.repair` does what the cause's detail tells a user to, a `password_file` line and an
   `OW_SECRET_*` variable in the fix child's environment (D643). `inflate` restores nothing
   either: its repair raises `[ingest] max_parts` through the twin the detail names (D644).
4. **fixed**: the verdict after the fix, which must be the pristine run's.

Each project has its own `HOME` and `OMNIWEAVE_HOME`, as `bench/serve/first_answer.py` lays them
out, so nothing of the user's is read or written. `ow add` and the fix are children; a query is
one read-only `execute()` in this process, which is what `ow query` runs (`surface/query.py`), so
the assertions read the `Verdict` itself and never the rendered prose.

**The fix runs as a child, not in this process. D640.** 13:1306 says *"in-process with no
shell"*, and the property that sentence protects is the second half: the argv is the parsed one
and nothing interprets it. A child is how the fix gets the fixture's own `HOME`, `OMNIWEAVE_HOME`
and working directory, which an in-process call would have to patch into this process's
`os.environ` and `os.chdir`, and a patch that leaked would make the next pair's run read the
previous pair's store.

## Exit codes

`0` every pair passed. `1` a pair failed. `2` the suite could not run: no register row, a fixture
that would not build, or an unknown `--injector`.
"""

