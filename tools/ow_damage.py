def emit(line: str = "") -> None:
    sys.stdout.write(line + "\n")
    sys.stdout.flush()


# ---------------------------------------------------------------------------------------------
# Building and reading a fixture
# ---------------------------------------------------------------------------------------------


def _generator() -> ModuleType:
    spec = importlib.util.spec_from_file_location("omniweave_gen_reference_corpora", GENERATOR)
    if spec is None or spec.loader is None:  # pragma: no cover -- the file is in this repo
        msg = f"cannot load {GENERATOR}"
        raise RuntimeError(msg)
    module = sys.modules.get(spec.name)
    if module is None:
        module = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = module
        spec.loader.exec_module(module)
    return module


def _documents(fixture: Fixture) -> dict[str, bytes]:
    wanted = set(fixture.paths)
    found = {
        doc.path: doc.to_bytes()
        for doc in _generator().documents(fixture.corpus, "quick")
        if doc.path in wanted
    }
    missing = wanted - set(found)
    if missing:
        msg = f"{fixture.corpus} has no {sorted(missing)} at quick scale"
        raise RuntimeError(msg)
    return found


def _env(work: Path) -> dict[str, str]:
    kept = {k: v for k, v in os.environ.items() if k not in {"PYTHONUTF8", "PYTHONIOENCODING"}}
    home = work / "home"
    home.mkdir(parents=True, exist_ok=True)
    return {**kept, "HOME": str(home), "USERPROFILE": str(home), "OMNIWEAVE_HOME": str(work / "ow")}


def _ow(work: Path, argv: Sequence[str], extra: Mapping[str, str] | None = None) -> Captured:
    """`ow <argv>` in `work/project`, as a child with no shell. Never raises (`run_captured`).

    `extra` is added to the fixture's environment: an `Injector.repair`'s secret, for the fix."""
    return run_captured(
        (sys.executable, "-m", "omniweave", *argv),
        stdin=b"",
        cwd=str(work / "project"),
        env={**_env(work), **(extra or {})},
        timeout_s=ADD_TIMEOUT_S,
    )


def build(work: Path, documents: Mapping[str, bytes], *, config: str = "") -> None:
    """Write the project and its documents under `work`, then `ow add docs`.

    `config` ends the project's `omniweave.toml`: an `Injector.config`, for a damaged build."""
    project = work / "project"
    (project / "docs").mkdir(parents=True)
    (project / "omniweave.toml").write_text(PROJECT + config, encoding="utf-8")
    for path, data in documents.items():
        target = project / "docs" / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    added = _ow(work, ("add", "docs"))
    if added.returncode != 0:
        tail = added.stderr.decode("utf-8", "replace")[-1200:]
        msg = f"ow add over {work} exited {added.returncode}:\n{tail}"
        raise RuntimeError(msg)


def ask(work: Path, question: str) -> Observed:
    """One read-only `execute()` over the fixture's store: `ow query`'s own read."""
    from omniweave_core.retrieve.execute import execute  # noqa: PLC0415
    from omniweave_core.retrieve.types import Query, RetrievalPolicy  # noqa: PLC0415
    from omniweave_core.store import reader as store_reader  # noqa: PLC0415
    from omniweave_core.store import sqlite as store_sqlite  # noqa: PLC0415

    connection = store_sqlite.connect_readonly(work / "project" / ".omniweave" / "docs.owstore")
    try:
        reader = store_reader.SqliteReader(connection, now_ns=time.time_ns())
        retrieval = execute(reader, Query(text=question), RetrievalPolicy())
    finally:
        connection.close()
    return observed(retrieval.response.verdict)


# ---------------------------------------------------------------------------------------------
# 13:1306: the fix, parsed against the registry
# ---------------------------------------------------------------------------------------------


def admit(argv: Sequence[str]) -> str | None:
    """`None` if `ow <argv>` names a runnable Action with that Action's parameters, else why not.

    Three checks, each one 13:1306 names:
    - the words resolve through `surface.registry.resolve_cli` to a verb, an argument or a bare
      root, and never to `no-such-root`, `no-such-verb`, `absent` or `unrostered`;
    - the root is one this build dispatches (`omniweave.__main__.DISPATCHED`), so it runs;
    - the whole argv parses under the generated CLI tree, so every flag is that Action's.
    """
    from omniweave.__main__ import DISPATCHED  # noqa: PLC0415
    from omniweave.cli import build_parser  # noqa: PLC0415
    from omniweave.surface.registry import resolve_cli  # noqa: PLC0415

    words = [word for word in argv[1:] if not word.startswith("-")]
    status = resolve_cli(words[:2])
    if status not in {"verb", "argument", "bare"}:
        return f"`{' '.join(words[:2])}` resolves as {status}, not as an Action"
    if words[0] not in DISPATCHED:
        return f"`ow {words[0]}` is an Action this build does not run"
    sink = io.StringIO()
    try:
        with contextlib.redirect_stderr(sink):
            build_parser().parse_args(list(argv[1:]))
    except SystemExit:
        return f"the parameters are not the Action's: {sink.getvalue().strip()}"
    return None


