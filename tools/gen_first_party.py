"""The first-party release manifest, from `dist/`: section 6.6 step 2. D895.

11-repo-layout.md section 7.2: *"Pass 1 builds all 28 files. `gen_first_party.py` reads the 26
non-core files and writes thirteen rows -- every first-party distribution except `omniweave-core`
itself. Pass 2 rebuilds only `omniweave-core`, whose wheel now contains the manifest."*

    uv run tools/gen_first_party.py --dist dist            # write the manifest into core's src/
    uv run tools/gen_first_party.py --dist dist --check    # assert the written one matches dist/

## Rulings

1. **One row per non-core wheel, keyed by its distribution name**, from the wheel's own
   `METADATA`. The sdists are the same release and carry no second digest: `dist_sha256` is the
   wheel's, because the wheel is what a user installs and what the loader can recompute.
2. **`dist_sha256` is `omniweave_core.drivers.digest.wheel_digest()`**, the `RECORD` digest of
   D576's first ruling, so the loader's `installed_digest()` over the same distribution agrees.
3. **`vendored` is G12's register's**: a distribution is vendored when a `tools/vendor.toml`
   `[[artefact]]` row's `pinned_by` is its `pyproject.toml`. G12 is what proves the four facts
   04-driver-system.md section 4.2's row 2 asks of a vendored driver, so the flag follows it.
4. **`release` defaults to `omniweave-core`'s version**, the `RELEASE` every other site carries
   (G5 reads this file's `release` as one of them).
5. **Exactly thirteen rows, or nothing is written.** Fourteen members minus core; a missing or
   extra wheel is a finding naming it, because a manifest one row short silently demotes that
   distribution to `unpinned` on every machine that installs the release.

Exit `0` written (or `--check` matched); `1` a finding; `2` the inputs could not be read.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
import zipfile
from email.parser import Parser
from pathlib import Path
from typing import TYPE_CHECKING, Final

from omniweave_core.drivers.catalog import FIRST_PARTY_NAME, FIRST_PARTY_SCHEMA
from omniweave_core.drivers.digest import wheel_digest

if TYPE_CHECKING:
    from collections.abc import Sequence

REPO: Final = Path(__file__).resolve().parent.parent
CORE: Final = "omniweave-core"
OUT: Final = (
    REPO / "packages" / "omniweave-core" / "src" / "omniweave_core" / "drivers" / FIRST_PARTY_NAME
)
EXIT_OK, EXIT_FINDING, EXIT_NOT_RUN = 0, 1, 2


def members(root: Path = REPO) -> dict[str, Path]:
    """Every workspace member's distribution name -> its `pyproject.toml`."""
    out = {}
    for pyproject in sorted((root / "packages").glob("*/pyproject.toml")):
        name = tomllib.loads(pyproject.read_text(encoding="utf-8")).get("project", {}).get("name")
        if name:
            out[str(name)] = pyproject
    return out


def vendored(root: Path = REPO) -> frozenset[str]:
    """Ruling 3: the distributions G12's register names as pinning a vendored artefact."""
    register = tomllib.loads((root / "tools" / "vendor.toml").read_text(encoding="utf-8"))
    pinned = {str(row.get("pinned_by", "")) for row in register.get("artefact", [])}
    return frozenset(
        name
        for name, pyproject in members(root).items()
        if pyproject.relative_to(root).as_posix() in pinned
    )


def wheel_identity(wheel: Path) -> tuple[str, str]:
    """`(name, version)` from the wheel's own `METADATA`."""
    with zipfile.ZipFile(wheel) as archive:
        (meta,) = [n for n in archive.namelist() if n.endswith(".dist-info/METADATA")]
        headers = Parser().parsestr(archive.read(meta).decode("utf-8"), headersonly=True)
    return str(headers["Name"]), str(headers["Version"])


def render(rows: dict[str, tuple[str, str, bool]], release: str) -> str:
    """The manifest, in section 7.2's printed shape, rows sorted by name."""
    lines = [
        f"# omniweave_core/drivers/{FIRST_PARTY_NAME} -- GENERATED by tools/gen_first_party.py. "
        f"{len(rows)} rows.",
        f"schema = {FIRST_PARTY_SCHEMA}",
        f'release = "{release}"',
    ]
    for name in sorted(rows):
        version, digest, is_vendored = rows[name]
        lines += ["", f'[dist."{name}"]', f'version = "{version}"', f'dist_sha256 = "{digest}"']
        if is_vendored:
            lines.append("vendored = true")
    return "\n".join(lines) + "\n"


def build(dist: Path, release: str | None) -> tuple[str, list[str]]:
    """Rulings 1-5: the manifest text, and every finding that should stop it being written."""
    names = members()
    expected = sorted(set(names) - {CORE})
    flagged = vendored()
    rows: dict[str, tuple[str, str, bool]] = {}
    findings: list[str] = []
    for wheel in sorted(dist.glob("*.whl")):
        name, version = wheel_identity(wheel)
        if name == CORE:
            continue
        if name not in names:
            findings.append(f"{wheel.name}: {name} is not a workspace member")
            continue
        if name in rows:
            findings.append(f"{wheel.name}: a second wheel for {name}")
            continue
        rows[name] = (version, wheel_digest(wheel), name in flagged)
    missing = [name for name in expected if name not in rows]
    findings += [f"no wheel for {name} in {dist}" for name in missing]
    core_version = tomllib.loads(names[CORE].read_text(encoding="utf-8"))["project"]["version"]
    return render(rows, release or str(core_version)), findings


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen_first_party", description="the first-party release manifest, from dist/"
    )
    parser.add_argument("--dist", type=Path, required=True, help="the built wheels")
    parser.add_argument("--release", help="RELEASE (default: omniweave-core's version)")
    parser.add_argument("--out", type=Path, default=OUT, help="where the manifest goes")
    parser.add_argument("--check", action="store_true", help="compare, do not write")
    args = parser.parse_args(argv)
    if not args.dist.is_dir():
        sys.stderr.write(f"{args.dist}: no such directory\n")
        return EXIT_NOT_RUN
    text, findings = build(args.dist, args.release)
    for finding in findings:
        sys.stdout.write(f"build.first_party_manifest FAIL  {finding}\n")
    if findings:
        return EXIT_FINDING
    if args.check:
        same = args.out.is_file() and args.out.read_text(encoding="utf-8") == text
        sys.stdout.write(
            f"build.first_party_manifest {'ok' if same else 'FAIL  stale'}  {args.out}\n"
        )
        return EXIT_OK if same else EXIT_FINDING
    args.out.write_bytes(text.encode("utf-8"))
    rows = text.count("[dist.")
    sys.stdout.write(f"build.first_party_manifest ok  {rows} rows -> {args.out}\n")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
